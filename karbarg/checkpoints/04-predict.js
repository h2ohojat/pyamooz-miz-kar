    var out = api.h('div', { class: 'callout' });
    var btn = api.h('button', { class: 'btn', type: 'button', text: 'حدس اولم را نشان بده' });
    btn.onclick = function () {
      var r = api.get('predict'), P = null;
      api.lesson.slides.forEach(function (s) { if (s.id === 'predict') P = s; });
      var t = r && r.choice != null && P ? P.options[r.choice].t : null;
      out.innerHTML = t ? 'اول کار گفتی: <b>' + t + '</b>' : 'هنوز حدسی ثبت نشده است؛ اول سؤال «حدس بزن» را جواب بده.';
    };
    el.appendChild(api.h('p', { text: 'یادت هست اول کار چه حدسی زدی؟' }));
    el.appendChild(btn);
    el.appendChild(out);
    el.appendChild(api.h('p', { class: 'muted', text: 'حالا چه فکر می‌کنی؟ چه چیزی نظرت را عوض کرد یا مطمئن‌ترت کرد؟' }));
